// Regenerates src/web/public/icons.js from lucide-react (ISC) so the plain-JS
// shell draws the DS icons without loading the React bundle.
import fs from "node:fs/promises";
import { format } from "prettier";
const names = {
  plus: "plus",
  refresh: "refresh-cw",
  external: "external-link",
  globe: "globe",
  braces: "braces",
  terminal: "square-terminal",
  image: "image",
  question: "circle-question-mark",
  alert: "triangle-alert",
  check: "circle-check",
  fail: "circle-x",
  pause: "circle-pause",
  timer: "timer",
  search: "search",
  panel: "panel-right",
  more: "ellipsis",
  back: "chevron-left",
  close: "x",
  help: "circle-question-mark",
  play: "circle-play",
};
const icons = {};
for (const [key, file] of Object.entries(names)) {
  const mod = await import(`lucide-react/dist/esm/icons/${file}.mjs`);
  icons[key] = mod.__iconData.node.map(([tag, { key: _, ...attrs }]) => [
    tag,
    attrs,
  ]);
}
const version = JSON.parse(
  await fs.readFile("node_modules/lucide-react/package.json", "utf8"),
).version;
await fs.writeFile(
  "src/web/public/icons.js",
  await format(
    `// Generated by scripts/icons.mjs from lucide-react v${version} (ISC license).
window.BrokerIcons = ${JSON.stringify(icons)};
`,
    { parser: "babel" },
  ),
);
